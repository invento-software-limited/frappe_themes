import os

import frappe

from frappe_themes.frappe_themes.doctype.theme.theme import MAINTENANCE_FLAG, get_theme_slug

THUMBNAIL_EXTENSIONS = (".webp", ".png", ".jpg", ".jpeg")


def sync_thumbnails():
	"""Load images from public/images/thumbnails/<theme slug>/ into each Theme's Thumbnails table.

	Images are generated by scripts/generate_thumbnails.mjs and named `<order>-<view-name>.<ext>`,
	e.g. `02-list-view.webp` becomes a row with View "List View".

	Run with: bench --site <site> execute frappe_themes.utils.thumbnails.sync_thumbnails
	"""
	base_dir = frappe.get_app_path("frappe_themes", "public", "images", "thumbnails")
	# Themes are fixed for users; this maintenance script is allowed to update their thumbnails
	frappe.flags[MAINTENANCE_FLAG] = True

	for theme_name in frappe.get_all("Theme", pluck="name"):
		folder = os.path.join(base_dir, get_theme_slug(theme_name))
		if not os.path.isdir(folder):
			continue

		theme = frappe.get_doc("Theme", theme_name)
		theme.set("thumbnails", [])
		for filename in sorted(os.listdir(folder)):
			stem, ext = os.path.splitext(filename)
			if ext.lower() not in THUMBNAIL_EXTENSIONS:
				continue
			theme.append(
				"thumbnails",
				{
					"view": get_view_label(stem),
					"image": f"/assets/frappe_themes/images/thumbnails/{get_theme_slug(theme_name)}/{filename}",
				},
			)
		theme.save()


def get_view_label(stem):
	"""`02-list-view` -> `List View`"""
	parts = stem.split("-")
	if parts[0].isdigit():
		parts = parts[1:]
	return " ".join(parts).title()
